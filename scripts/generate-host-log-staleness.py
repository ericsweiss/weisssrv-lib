#!/usr/bin/env python3
"""Generate the host log-shipping staleness rules from the Ansible inventory.

One cluster-wide rule plus one per targeted host. Exit 0 written or in step, 1 on
drift under --check, 2 when an input or the output cannot be read or written.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover - environment guard
    print("ERROR: PyYAML required: pip install pyyaml", file=sys.stderr)
    raise SystemExit(2) from None

sys.path.insert(0, str(Path(__file__).resolve().parent))

try:
    import inventory_tree  # noqa: E402  (resolved from this script's own directory)
except ImportError as exc:  # pragma: no cover - environment guard
    print(
        f"ERROR: {exc.name or 'inventory_tree'}.py must sit next to this script "
        "- vendor it (see weisssrv-lib scripts/vendorable-paths.yml).",
        file=sys.stderr,
    )
    raise SystemExit(2) from None

REPO = Path(__file__).resolve().parent.parent
SITE_YML = "ansible/playbooks/site.yml"
HOSTS_YML = "ansible/inventories/prod/hosts.yml"
OUTPUT = "kubernetes/infrastructure/observability/loki/host-log-staleness.yaml"
ROLE = "alloy_host"
SYNC = "task flux:sync-host-log-staleness"

HEADER = """\
---
# GENERATED by scripts/generate-host-log-staleness.py from the {role} play in
# {site_yml}. Run `{sync}` after an inventory change.
# Host journald ships as {{job="journal"}}.
groups:
  - name: host-log-staleness
    interval: 1m
    rules:
      - alert: HostLogShippingStaleAll
        expr: absent_over_time({{job="journal"}}[45m])
        for: 15m
        labels: {{ severity: warning, component: logging }}
        annotations:
          summary: "No journald logs from ANY host in 45m (host log shipping stopped cluster-wide)"
          description: >-
            No journald line has reached Loki from any host in 45 minutes. Check
            the host-side collector unit on one host, then the Loki push
            IngressRoute and the Loki pod.
          runbook_url: "${{cluster_runbook_base_url}}/{runbook}"
"""

DESCRIPTION = (
    "No journald line has reached Loki from {{ $labels.host }} in 45m. Its "
    "host-side Alloy is dead, the host is down, or the Loki push path is broken "
    "past the on-disk WAL. Check `systemctl status alloy` on {{ $labels.host }}, "
    "then the loki.${cluster_internal_domain} IngressRoute and the Loki pod."
)


class OperatorError(Exception):
    """The generator could not read its source: exit 2, never an empty file."""


def _role_names(play: dict) -> list[str]:
    """Short role names in a play's `roles:` list; roles ship FQCN'd."""
    names = []
    for entry in play.get("roles") or []:
        role = entry.get("role") if isinstance(entry, dict) else entry
        if isinstance(role, str) and role:
            names.append(role.rsplit(".", 1)[-1])
    return names


def target_groups(site_yml: Path, role: str = ROLE) -> tuple[list[str], list[str]]:
    """The play's included and `!`-excluded tokens, groups or hosts, in written order.

    An excluded host never runs the role, so it ships no journald and gets no
    rule; alerting on it would fire forever.
    """
    try:
        # The handle, not the text: PyYAML names the file in its error mark.
        with site_yml.open(encoding="utf-8") as handle:
            plays = yaml.safe_load(handle)
    except (OSError, UnicodeDecodeError, yaml.YAMLError) as exc:
        raise OperatorError(f"{site_yml} unreadable: {exc}") from exc
    if not isinstance(plays, list):
        raise OperatorError(f"{site_yml}: not a list of plays")
    matches = [p for p in plays if isinstance(p, dict) and role in _role_names(p)]
    if len(matches) != 1:
        raise OperatorError(f"{site_yml}: expected exactly one {role} play, found {len(matches)}")
    expression = matches[0].get("hosts")
    if not expression:
        raise OperatorError(f"{site_yml}: the {role} play has no hosts: pattern")
    parts = expression if isinstance(expression, list) else [expression]
    tokens = [t for part in parts for t in str(part).split(":") if t]
    return (
        [t for t in tokens if not t.startswith("!")],
        [t.lstrip("!") for t in tokens if t.startswith("!")],
    )


def role_hosts(
    root: Path, site_yml: str = SITE_YML, hosts_yml: str = HOSTS_YML, role: str = ROLE
) -> list[str]:
    """The play's host set, in the order the playbook and inventory produce it."""
    try:
        inventory = inventory_tree.load_inventory(root / hosts_yml)
        index = inventory_tree.group_index(inventory)
    except (OSError, UnicodeDecodeError, yaml.YAMLError) as exc:
        raise OperatorError(f"{hosts_yml} unreadable: {exc}") from exc
    groups, excludes = target_groups(root / site_yml, role)
    declared = inventory_tree.declared_groups(inventory)
    known_hosts = set(inventory_tree.all_hosts(inventory))

    def resolve(token: str) -> list[str] | None:
        """A group's hosts, a host itself, [] for an empty group, None if unknown."""
        try:
            if token in index:
                return inventory_tree.resolve_hosts(token, index, strict=True)
        except inventory_tree.InventoryCycle as exc:
            raise OperatorError(str(exc)) from exc
        if token in known_hosts:
            return [token]
        return [] if token in declared else None

    ordered: list[str] = []
    for token in groups:
        hosts = resolve(token)
        if hosts is None:
            raise OperatorError(
                f"the play targets {token!r}, which the inventory declares as "
                "neither a group nor a host"
            )
        ordered += [host for host in hosts if host not in ordered]
    excluded: set[str] = set()
    for token in excludes:
        hosts = resolve(token)
        if hosts is None:
            # Ansible only warns on an unknown exclusion, such as a runtime-only group.
            print(
                f"generate-host-log-staleness: warning: the play excludes {token!r}, "
                "which the inventory declares as neither a group nor a host",
                file=sys.stderr,
            )
        excluded.update(hosts or ())
    ordered = [host for host in ordered if host not in excluded]
    if not ordered:
        raise OperatorError(f"the {role} play resolved to no hosts")
    return ordered


def render(
    hosts: list[str],
    runbook: str,
    role: str = ROLE,
    site_yml: str = SITE_YML,
    sync: str = SYNC,
) -> str:
    body = [HEADER.format(role=role, site_yml=site_yml, sync=sync, runbook=runbook)]
    for host in hosts:
        body.append(
            f'      - alert: HostLogShippingStale\n'
            f'        expr: absent_over_time({{job="journal", host="{host}"}}[45m])\n'
            f'        for: 15m\n'
            f"        labels: {{ severity: warning, component: logging, "
            f"host: {host}, instance: {host} }}\n"
            f"        annotations:\n"
            f'          summary: "No journald logs from {{{{ $labels.host }}}} in 45m '
            f'({role} shipping stopped)"\n'
            f'          description: "{DESCRIPTION}"\n'
            f'          runbook_url: "${{cluster_runbook_base_url}}/{runbook}"\n'
        )
    return "".join(body)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Generate the HostLogShippingStale rules")
    parser.add_argument("--repo-root", default=str(REPO))
    parser.add_argument(
        "--runbook",
        required=True,
        help="runbook path and anchor appended to ${cluster_runbook_base_url}/",
    )
    parser.add_argument("--output", default=OUTPUT, help="rule file, relative to the repo root")
    parser.add_argument("--site-yml", default=SITE_YML, help="playbook holding the role's play")
    parser.add_argument("--hosts-yml", default=HOSTS_YML, help="inventory hosts file")
    parser.add_argument("--role", default=ROLE, help="the log-shipping role's short name")
    parser.add_argument("--sync-command", default=SYNC, help="command the header and errors name")
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    parser.add_argument(
        "--count",
        action="store_true",
        help="print the rule count a regenerated file carries: hosts plus the cluster-wide rule",
    )
    args = parser.parse_args(argv)
    root = Path(args.repo_root)

    try:
        hosts = role_hosts(root, args.site_yml, args.hosts_yml, args.role)
    except OperatorError as exc:
        print(f"generate-host-log-staleness: {exc}", file=sys.stderr)
        return 2

    if args.count:
        print(len(hosts) + 1)
        return 0

    wanted = render(hosts, args.runbook, args.role, args.site_yml, args.sync_command)
    target = root / args.output
    try:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
    except (OSError, UnicodeDecodeError) as exc:
        print(f"generate-host-log-staleness: {args.output} unreadable: {exc}", file=sys.stderr)
        return 2
    if args.check:
        # The write path replaces the whole file, header included, so a
        # hand-edited header is drift too.
        if current != wanted:
            print(
                f"{args.output} is stale ({len(hosts)} {args.role} hosts in the inventory): "
                f"run `{args.sync_command}`",
                file=sys.stderr,
            )
            return 1
        print(f"{args.output} is in step with the inventory ({len(hosts)} hosts).")
        return 0
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(wanted, encoding="utf-8")
    except OSError as exc:
        print(f"generate-host-log-staleness: cannot write {args.output}: {exc}", file=sys.stderr)
        return 2
    print(f"Wrote {args.output} ({len(hosts)} hosts).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
